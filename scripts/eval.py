"""Run the golden dataset against the real agent and report the results.

Each case starts a fresh session (optionally at its own reference date),
sends the customer messages in order and checks, deterministically:
- expected_tools: every listed tool was called at some point in the case (an
  item that is a list passes if any of its tools was called);
- must_contain: every item appears in the final answer (an item that is a list
  passes if any of its alternatives appears);
- must_not_contain: none of these appear in any answer of the case.
Texts are compared lowercase and without accents. No LLM judges the answers.

Usage: python scripts/eval.py [--only CASE_ID ...]
Writes evals/last_run.md and prints the summary metrics.
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
import uuid
from dataclasses import dataclass, field, replace
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from emporio_agent.agent import Agent, TurnResult  # noqa: E402
from emporio_agent.config import Settings, load_settings, parse_reference_date  # noqa: E402
from emporio_agent.data import StoreData, load_store_data, normalize_text  # noqa: E402
from emporio_agent.llm import OpenAIClient  # noqa: E402
from emporio_agent.policies import PolicyManual, load_policy_manual  # noqa: E402
from emporio_agent.tracing import Tracer, estimate_cost  # noqa: E402

DATASET = ROOT / "evals" / "golden_dataset.jsonl"
REPORT = ROOT / "evals" / "last_run.md"
DEFAULT_REFERENCE_DATE = "2026-03-25T10:00"


@dataclass
class CaseResult:
    case_id: str
    passed: bool
    failures: list[str]
    tools: list[str]
    turns: list[TurnResult] = field(default_factory=list)
    final_answer: str = ""


def load_cases(path: Path = DATASET) -> list[dict]:
    lines = path.read_text(encoding="utf-8").splitlines()
    return [json.loads(line) for line in lines if line.strip()]


def _contains(text: str, item: str | list[str]) -> bool:
    options = item if isinstance(item, list) else [item]
    return any(normalize_text(option) in text for option in options)


def check_case(case: dict, answers: list[str], tools: list[str]) -> list[str]:
    """Deterministic checks for one case. Returns the failures (empty = pass)."""
    failures = []
    for tool in case.get("expected_tools", []):
        options = tool if isinstance(tool, list) else [tool]
        if not any(option in tools for option in options):
            failures.append(f"tool not called: {tool}")
    final = normalize_text(answers[-1]) if answers else ""
    for item in case.get("must_contain", []):
        if not _contains(final, item):
            failures.append(f"missing: {item}")
    every_answer = normalize_text(" ".join(answers))
    for item in case.get("must_not_contain", []):
        if _contains(every_answer, item):
            failures.append(f"must not contain: {item}")
    return failures


def run_case(case: dict, llm, store: StoreData, manual: PolicyManual, settings: Settings,
             tracer: Tracer | None = None) -> CaseResult:
    now = parse_reference_date(case.get("reference_date", DEFAULT_REFERENCE_DATE))
    agent = Agent(llm, store, manual, replace(settings, reference_now=now))
    turns = []
    for message in case["messages"]:
        turn = agent.respond(message)
        turns.append(turn)
        if tracer:
            tracer.record(turn, message, now)
    tools = [call.name for turn in turns for call in turn.tool_calls]
    answers = [turn.answer for turn in turns]
    failures = check_case(case, answers, tools)
    return CaseResult(case["id"], not failures, failures, tools, turns, answers[-1])


def summarize(results: list[CaseResult], model: str) -> dict:
    turns = [t for r in results for t in r.turns]
    costs = [estimate_cost(model, t.prompt_tokens, t.completion_tokens) for t in turns]
    known_costs = [c for c in costs if c is not None]
    return {
        "cases": len(results),
        "passed": sum(r.passed for r in results),
        "pass_rate": sum(r.passed for r in results) / len(results) if results else 0.0,
        "messages": len(turns),
        "avg_cost_per_message_usd": statistics.mean(known_costs) if known_costs else None,
        "median_latency_ms": statistics.median(t.latency_ms for t in turns) if turns else None,
        "guardrail_triggers": sum(t.guardrail_triggered for t in turns),
        "errors": sum(t.error_type is not None for t in turns),
    }


def render(results: list[CaseResult], metrics: dict, model: str, ran_at: datetime) -> str:
    cost = metrics["avg_cost_per_message_usd"]
    lines = [
        "# Eval — last run",
        "",
        f"Generated by `python scripts/eval.py` on {ran_at:%Y-%m-%d %H:%M} with model `{model}`. "
        "Checks are deterministic (tools called, required and forbidden text); no LLM judge.",
        "",
        f"**{metrics['passed']}/{metrics['cases']} cases passed ({metrics['pass_rate']:.0%})** · "
        f"{metrics['messages']} messages · median latency {metrics['median_latency_ms']:.0f} ms per "
        f"message · average cost "
        + (f"US$ {cost:.5f}" if cost is not None else "n/a")
        + f" per message · guardrail triggered {metrics['guardrail_triggers']}x · "
        f"{metrics['errors']} fallback answers",
        "",
        "| Case | Result | Tools called | Failures |",
        "|---|---|---|---|",
    ]
    for r in results:
        tools = ", ".join(dict.fromkeys(r.tools)) or "—"
        failures = "; ".join(r.failures).replace("|", "/") or ""
        lines.append(f"| `{r.case_id}` | {'✅' if r.passed else '❌'} | {tools} | {failures} |")
    lines += ["", "## Final answers", ""]
    for r in results:
        answer = r.final_answer.replace("\n", "\n> ")
        lines += [f"**`{r.case_id}`** {'✅' if r.passed else '❌'}", "", f"> {answer}", ""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Run the golden dataset.")
    parser.add_argument("--only", nargs="*", help="run only these case ids")
    args = parser.parse_args()
    for stream in (sys.stdout,):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):
            pass

    settings = load_settings()
    settings = replace(settings, handoffs_path=settings.logs_dir / "eval_handoffs.jsonl")
    store, manual = load_store_data(), load_policy_manual()
    llm = OpenAIClient(settings)
    tracer = Tracer(settings.logs_dir / "eval_traces.jsonl", "eval-" + uuid.uuid4().hex[:6],
                    settings.model)

    cases = load_cases()
    if args.only:
        cases = [c for c in cases if c["id"] in args.only]
    results = []
    for case in cases:
        result = run_case(case, llm, store, manual, settings, tracer)
        results.append(result)
        status = "PASS" if result.passed else "FAIL"
        print(f"{status}  {result.case_id}" + (f"  ({'; '.join(result.failures)})" if result.failures else ""))

    metrics = summarize(results, settings.model)
    REPORT.write_text(render(results, metrics, settings.model, datetime.now()), encoding="utf-8")
    print(f"\n{metrics['passed']}/{metrics['cases']} passed ({metrics['pass_rate']:.0%}). "
          f"Report: {REPORT.relative_to(ROOT)}")
    print(json.dumps(metrics, indent=2, default=str))
    return 0 if metrics["passed"] == metrics["cases"] else 1


if __name__ == "__main__":
    sys.exit(main())
